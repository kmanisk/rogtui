use ratatui::style::{Color, Modifier, Style};
use serde::Deserialize;
use std::fs;
use std::path::PathBuf;

use crate::backend::types::{PlatformProfile, RgbColor};

#[derive(Debug, Clone, Copy)]
pub struct Theme {
    pub accent: Color,
    pub ok: Color,
    pub warn: Color,
    pub err: Color,
    pub dim: Color,
    pub fg: Color,
    pub sel_bg: Color,
    pub sel_fg: Color,
}

impl Default for Theme {
    fn default() -> Self {
        Self {
            accent: Color::Cyan,
            ok: Color::Green,
            warn: Color::Yellow,
            err: Color::Red,
            dim: Color::DarkGray,
            fg: Color::White,
            sel_bg: Color::Cyan,
            sel_fg: Color::Black,
        }
    }
}

impl Theme {
    pub fn load_or_default() -> Self {
        let config_dir = std::env::var("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .or_else(|_| std::env::var("HOME").map(|h| PathBuf::from(h).join(".config")))
            .ok();

        if let Some(config_dir) = config_dir {
            let path = config_dir.join("rogtui").join("theme.toml");
            if path.exists() {
                if let Ok(content) = fs::read_to_string(&path) {
                    if let Ok(theme) = toml::from_str::<ThemeFile>(&content) {
                        return theme.into_theme();
                    }
                }
            }
        }
        Self::default()
    }

    /// Convert the active UI accent color into an RgbColor.
    pub fn accent_rgb(&self) -> RgbColor {
        match self.accent {
            Color::Cyan => RgbColor::new(0, 220, 255),
            Color::Green => RgbColor::new(0, 220, 100),
            Color::Yellow => RgbColor::new(240, 200, 0),
            Color::Red => RgbColor::new(255, 60, 60),
            Color::Blue => RgbColor::new(60, 140, 255),
            Color::Magenta => RgbColor::new(255, 80, 220),
            Color::Rgb(r, g, b) => RgbColor::new(r, g, b),
            _ => RgbColor::new(0, 220, 255),
        }
    }

    /// Read the active desktop theme from ~/.local/state/theme/colors.sh (auto-generated by theme-set)
    /// and determine the dominant aesthetic color for static keyboard lighting.
    /// Supports Gruvbox (grayish-cream #EBDBB2), Catppuccin (pinkish #F5C2E7), etc.
    pub fn get_system_theme_color() -> (String, RgbColor) {
        if let Ok(home) = std::env::var("HOME") {
            let path = PathBuf::from(home).join(".local/state/theme/colors.sh");
            if let Ok(content) = fs::read_to_string(&path) {
                let mut name = String::new();
                let mut accent = None;
                let mut fg = None;
                for line in content.lines() {
                    let trimmed = line.trim();
                    if let Some(n) = trimmed.strip_prefix("export THEME_NAME=") {
                        name = n.trim_matches('"').to_string();
                    } else if let Some(a) = trimmed.strip_prefix("export THEME_ACCENT=") {
                        accent = RgbColor::from_hex(a.trim_matches('"')).ok();
                    } else if let Some(f) = trimmed.strip_prefix("export THEME_FG=") {
                        fg = RgbColor::from_hex(f.trim_matches('"')).ok();
                    }
                }
                if name.eq_ignore_ascii_case("gruvbox") {
                    return ("Gruvbox".to_string(), fg.unwrap_or(RgbColor::new(235, 219, 178)));
                } else if name.eq_ignore_ascii_case("catppuccin") {
                    return ("Catppuccin".to_string(), RgbColor::new(245, 194, 231));
                } else if let Some(acc) = accent {
                    let label = if name.is_empty() { "Theme".to_string() } else { name };
                    return (label, acc);
                }
            }
        }
        ("Theme".to_string(), RgbColor::new(0, 220, 255))
    }

    pub fn sel_style(&self) -> Style {
        Style::default()
            .bg(self.sel_bg)
            .fg(self.sel_fg)
            .add_modifier(Modifier::BOLD)
    }

    pub fn profile_color(&self, profile: PlatformProfile) -> Color {
        match profile {
            PlatformProfile::Quiet => Color::Blue,
            PlatformProfile::Balanced => self.ok,
            PlatformProfile::Performance => self.err,
            PlatformProfile::Custom => Color::Magenta,
        }
    }

    pub fn temp_color(&self, temp_c: u32) -> Color {
        if temp_c < 70 {
            self.ok
        } else if temp_c <= 85 {
            self.warn
        } else {
            self.err
        }
    }

    pub fn usage_color(&self, percent: u32) -> Color {
        if percent < 60 {
            self.ok
        } else if percent <= 85 {
            self.warn
        } else {
            self.err
        }
    }
}

#[derive(Debug, Deserialize)]
struct ThemeFile {
    pub accent: Option<String>,
    pub ok: Option<String>,
    pub warn: Option<String>,
    pub err: Option<String>,
    pub dim: Option<String>,
    pub fg: Option<String>,
    pub sel_bg: Option<String>,
    pub sel_fg: Option<String>,
}

impl ThemeFile {
    fn parse_color(s: Option<&str>, default: Color) -> Color {
        match s {
            Some(v) => match v.to_lowercase().as_str() {
                "black" => Color::Black,
                "red" => Color::Red,
                "green" => Color::Green,
                "yellow" => Color::Yellow,
                "blue" => Color::Blue,
                "magenta" => Color::Magenta,
                "cyan" => Color::Cyan,
                "gray" | "grey" => Color::Gray,
                "darkgray" | "darkgrey" => Color::DarkGray,
                "white" => Color::White,
                _ => default,
            },
            None => default,
        }
    }

    fn into_theme(self) -> Theme {
        let def = Theme::default();
        Theme {
            accent: Self::parse_color(self.accent.as_deref(), def.accent),
            ok: Self::parse_color(self.ok.as_deref(), def.ok),
            warn: Self::parse_color(self.warn.as_deref(), def.warn),
            err: Self::parse_color(self.err.as_deref(), def.err),
            dim: Self::parse_color(self.dim.as_deref(), def.dim),
            fg: Self::parse_color(self.fg.as_deref(), def.fg),
            sel_bg: Self::parse_color(self.sel_bg.as_deref(), def.sel_bg),
            sel_fg: Self::parse_color(self.sel_fg.as_deref(), def.sel_fg),
        }
    }
}
